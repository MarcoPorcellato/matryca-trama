class SyntheticDemoGateway:
    """Implements KnowledgeGraphGateway using authored values, without I/O."""

    def snapshot(self) -> GraphSnapshot:
        nodes = tuple(
            TopologyNode(f"n{i}", NodeKind.PAGE, None, i - 1)
            for i in range(1, len(ANNOTATIONS) + 1)
        )
        edges = tuple(ReferenceEdge(f"n{a}", f"n{b}") for a, b in REFERENCES)
        return GraphSnapshot(
            GraphIdentity("synthetic-demo", "fictional-session", "fictional-v1"),
            GraphTopology("fictional-topology", nodes, edges),
            SnapshotProvenance(
                "synthetic-demo",
                "authored-fixture",
                "not-a-producer-artifact",
                "not-a-plumber-descriptor",
                "not-runtime-evidence",
            ),
        )
